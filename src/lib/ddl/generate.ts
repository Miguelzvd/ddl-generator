/** Monta o script SQL comentado a partir dos planos de tabela. */
import type { EntityReport, GenerateOptions, Status } from '../model';
import { ident, identList } from './ident';
import type { JoinTablePlan } from './joinTable';
import { columnName, type Registry } from './naming';
import { planTable, type PlannedColumn, type PlannedFk, type TablePlan } from './plan';

const RULE = '-- ' + '='.repeat(72);
const SUB = '-- ' + '-'.repeat(72);
const DEFAULT_SCHEMA = '(schema do usuário conectado)';
const GENERATED = new Set<Status>(['ok', 'assumptions', 'revised']);

/** Texto entre aspas simples, com `'` escapado. */
export const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`;

function fmtDate(d: Date) {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${p(d.getDate())}/${p(d.getMonth() + 1)}/${d.getFullYear()} ${p(d.getHours())}:${p(d.getMinutes())}`;
}

function columnLines(cols: PlannedColumn[], pk: string[]) {
  const width = Math.max(...cols.map((c) => ident(c.name).length));
  const lines: string[] = [];
  for (const c of cols) {
    for (const n of c.notes) lines.push(`  -- Revisado: ${n}`);
    for (const w of c.warnings) lines.push(`  -- ATENÇÃO: ${w}`);
    let line = `  ${ident(c.name).padEnd(width)} ${c.sql}`;
    if (c.identity) line += ' GENERATED BY DEFAULT AS IDENTITY';
    if (c.default !== undefined) line += ` DEFAULT ${c.default}`;
    if (!c.identity && (!c.nullable || pk.includes(c.name))) line += ' NOT NULL';
    lines.push(line + ',');
  }
  return lines;
}

function createTable(qn: string, cols: PlannedColumn[], pk: string[], pkName: string) {
  const lines = [`CREATE TABLE ${qn} (`, ...columnLines(cols, pk)];
  if (pk.length) {
    lines.push(`  CONSTRAINT ${pkName} PRIMARY KEY (${identList(pk)})`);
  } else {
    lines.push('  -- ATENÇÃO: entity sem chave primária declarada');
    lines[lines.length - 2] = lines[lines.length - 2].replace(/,$/, '');
  }
  lines.push(');');
  return lines;
}

function tableBlock(plan: TablePlan) {
  const e = plan.entity;
  const out = ['', `-- Tabela ${plan.qualifiedName}`, `-- Entity: ${e.className} (${e.file})`];
  for (const n of plan.tableNotes) out.push(`-- Revisado: ${n}`);
  if (plan.sequenceName) {
    const idCol = plan.columns.find((c) => e.columns.some((m) => m.generated && columnName(m) === c.name));
    out.push(`-- Sequence para a chave gerada (${idCol?.name ?? 'PK'}): use ${plan.sequenceName}.NEXTVAL ao inserir`);
    out.push(`CREATE SEQUENCE ${plan.sequenceName} START WITH 1 INCREMENT BY 1 NOCACHE;`);
  }
  out.push(...createTable(plan.qualifiedName, plan.columns, plan.pk, plan.pkName));
  out.push(`COMMENT ON TABLE ${plan.qualifiedName} IS ${sqlString(`Entity ${e.className} (${e.file})`)};`);
  for (const c of plan.columns) {
    const desc = c.fromRelation ? `Coluna da relação ${c.property}` : `Propriedade ${c.property}`;
    out.push(`COMMENT ON COLUMN ${plan.qualifiedName}.${ident(c.name)} IS ${sqlString(desc)};`);
  }
  for (const inv of plan.inverseRelations) out.push(`-- Relação sem FK nesta tabela: ${inv}`);
  return out;
}

function joinTableBlock(jt: JoinTablePlan) {
  return ['', `-- ${jt.description}`, ...createTable(jt.qualifiedName, jt.columns, jt.pk, jt.pkName), `COMMENT ON TABLE ${jt.qualifiedName} IS ${sqlString(jt.description)};`];
}

function fkLines(fk: PlannedFk) {
  const stmt = `ALTER TABLE ${fk.table} ADD CONSTRAINT ${fk.name} FOREIGN KEY (${identList(fk.columns)}) REFERENCES ${fk.refTable} (${identList(fk.refColumns)});`;
  const head = [`-- ${fk.description}`, ...(fk.note ? [`-- Revisado: ${fk.note}`] : [])];
  if (fk.active) return [...head, stmt];
  return [...head, `-- MOTIVO: ${fk.reason}`, `-- ${stmt}`];
}

function header(plans: TablePlan[], views: EntityReport[], allFks: PlannedFk[], opts: GenerateOptions, meta: Meta) {
  const activeFks = allFks.filter((f) => f.active).length;
  return [
    RULE,
    '-- DDL Oracle gerado a partir de entities TypeORM',
    `-- Origem: ${meta.source}`,
    `-- Gerado em: ${fmtDate(meta.now ?? new Date())}`,
    `-- Tabelas: ${plans.length} | FKs: ${activeFks} ativas, ${allFks.length - activeFks} comentadas | Views listadas: ${views.length}`,
    `-- Chave gerada: ${opts.oracle11g ? 'SEQUENCE (Oracle 11g)' : 'IDENTITY (Oracle 12c+)'}`,
    '-- Legenda: "-- ATENÇÃO:" marca valores presumidos; FKs comentadas trazem "-- MOTIVO:".',
    RULE,
  ];
}

function viewsBlock(views: EntityReport[]) {
  const out = ['', SUB, '-- Views encontradas (sem DDL)', '-- O SELECT que define cada view não está no código da entity;', '-- abaixo, só as colunas que a aplicação espera.', SUB];
  for (const v of views) {
    const e = v.entity!;
    out.push('', `-- View ${e.schema ? `${e.schema}.` : ''}${e.tableName} — ${e.className} (${e.file})`);
    for (const c of e.columns) out.push(`--   ${columnName(c)}${c.tsType ? ` (${c.tsType})` : ''}`);
  }
  return out;
}

interface Meta {
  source: string;
  now?: Date;
}

/**
 * Gera o script. `reports` traz as tabelas escolhidas (ok/suposições/revisado)
 * e as views, que só são listadas em comentário.
 */
export function generateDdl(reports: EntityReport[], registry: Registry, opts: GenerateOptions, meta: Meta): string {
  const seen = new Set<string>();
  const plans: TablePlan[] = [];
  const views: EntityReport[] = [];

  for (const r of reports) {
    if (!r.entity) continue;
    if (r.kind === 'view') {
      views.push(r);
      continue;
    }
    if (!GENERATED.has(r.status)) continue;
    const plan = planTable(r.entity, registry, opts);
    if (seen.has(plan.qualifiedName)) continue;
    seen.add(plan.qualifiedName);
    plans.push(plan);
  }

  const bySchema = new Map<string, TablePlan[]>();
  for (const p of plans) {
    const key = p.entity.schema ?? '';
    if (!bySchema.has(key)) bySchema.set(key, []);
    bySchema.get(key)!.push(p);
  }
  const schemas = [...bySchema.keys()].sort((a, b) => (a === '' ? -1 : b === '' ? 1 : a.localeCompare(b)));
  const allFks = plans.flatMap((p) => [...p.fks, ...p.joinTables.flatMap((j) => j.fks)]);
  const out = header(plans, views, allFks, opts, meta);

  for (const s of schemas) {
    out.push('', SUB, `-- Schema: ${s || DEFAULT_SCHEMA}`, SUB);
    for (const p of bySchema.get(s)!) {
      out.push(...tableBlock(p));
      for (const jt of p.joinTables) {
        if (seen.has(jt.qualifiedName)) continue;
        seen.add(jt.qualifiedName);
        out.push(...joinTableBlock(jt));
      }
    }
  }

  if (allFks.length) {
    out.push('', SUB, '-- Chaves estrangeiras (criadas no fim para não depender da ordem das tabelas)', SUB);
    for (const fk of allFks) out.push('', ...fkLines(fk));
  }

  const indices = plans.flatMap((p) => p.indices);
  if (indices.length) {
    out.push('', SUB, '-- Índices', SUB);
    for (const ix of indices) out.push(`CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${ix.name} ON ${ix.table} (${identList(ix.columns)});`);
  }

  if (views.length) out.push(...viewsBlock(views));
  return out.join('\n') + '\n';
}
