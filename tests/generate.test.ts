import { describe, expect, it } from 'vitest';
import { buildReports } from '../src/analysis/classify';
import { generateDdl } from '../src/ddl/generate';
import type { GenerateOptions, ParsedFile } from '../src/model';
import { parseFile } from '../src/parser/parseFile';
import { parseFixture } from './helpers';

function gen(files: ParsedFile[], opts: GenerateOptions = { oracle11g: false }) {
  const { reports, registry } = buildReports(files);
  const usable = reports.filter((r) => r.status === 'ok' || r.status === 'assumptions' || r.status === 'revised' || r.kind === 'view');
  return generateDdl(usable, registry, opts, { source: 'teste', now: new Date(2026, 10, 13, 10, 0) });
}

const all = () => [
  parseFixture('Cliente'),
  parseFixture('Produto'),
  parseFixture('Categoria'),
  parseFixture('Marca'),
  parseFixture('ClienteResumoV'),
];

describe('generateDdl', () => {
  it('gera CREATE TABLE com PK, default e NOT NULL', () => {
    const sql = gen(all());
    expect(sql).toContain('CREATE TABLE LOJA.CLIENTE (');
    expect(sql).toContain('CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE)');
    expect(sql).toMatch(/DATA_CADASTRO\s+DATE\s+DEFAULT SYSDATE NOT NULL/);
    expect(sql).toMatch(/ATIVO\s+NUMBER\s+NOT NULL/);
    expect(sql).toMatch(/\n\s+NOME\s+VARCHAR2\(255\),/);
    expect(sql).toContain("COMMENT ON TABLE LOJA.CLIENTE IS 'Entity Cliente (loja/Cliente.ts)';");
  });

  it('usa IDENTITY por padrão', () => {
    const sql = gen(all());
    expect(sql).toMatch(/ID_PRODUTO\s+NUMBER GENERATED BY DEFAULT AS IDENTITY/);
    expect(sql).not.toContain('CREATE SEQUENCE');
  });

  it('com Oracle 11g usa SEQUENCE', () => {
    const sql = gen(all(), { oracle11g: true });
    expect(sql).toContain('CREATE SEQUENCE SQ_PRODUTO START WITH 1 INCREMENT BY 1 NOCACHE;');
    expect(sql).not.toContain('IDENTITY');
  });

  it('marca suposições com ATENÇÃO', () => {
    expect(gen(all())).toContain('-- ATENÇÃO: tamanho não definido na entity; usado VARCHAR2(255)');
  });

  it('FK incompatível sai comentada com o motivo', () => {
    const sql = gen(all());
    expect(sql).toContain(
      '-- ALTER TABLE PRODUTO ADD CONSTRAINT FK_PRODUTO_ID_MARCA FOREIGN KEY (ID_MARCA) REFERENCES MARCA (COD_MARCA);',
    );
    expect(sql).toMatch(/-- MOTIVO: .*ORA-02267/);
  });

  it('FK compatível sai ativa', () => {
    const sql = gen([
      parseFile('a.ts', `@Entity('PAI') class Pai { @PrimaryGeneratedColumn({name:'ID'}) id: number }`),
      parseFile('b.ts', `@Entity('FILHO') class Filho { @PrimaryGeneratedColumn({name:'ID'}) id: number
        @ManyToOne(() => Pai) @JoinColumn({name:'PAI_ID'}) pai: Pai }`),
    ]);
    expect(sql).toMatch(/^ALTER TABLE FILHO ADD CONSTRAINT FK_FILHO_PAI_ID FOREIGN KEY \(PAI_ID\) REFERENCES PAI \(ID\);$/m);
  });

  it('lista views no fim, sem DDL', () => {
    const sql = gen(all());
    const idx = sql.indexOf('Views encontradas (sem DDL)');
    expect(idx).toBeGreaterThan(0);
    expect(sql.slice(idx)).toContain('CLIENTE_RESUMO_V');
    expect(sql.slice(idx)).toContain('ID_GRUPO');
    expect(sql).not.toContain('CREATE TABLE CLIENTE_RESUMO_V');
  });

  it('escapa aspas simples nos comentários', () => {
    const sql = gen([parseFile("o'brien.ts", `@Entity('T') class T { @PrimaryColumn('number',{name:'ID'}) id: number }`)]);
    expect(sql).toContain("IS 'Entity T (o''brien.ts)';");
  });

  it('trunca nomes de constraint a 30 com Oracle 11g', () => {
    const longo = parseFile('x.ts', `@Entity('MOVIMENTACAO_ESTOQUE_FILIAIS') class Mov { @PrimaryGeneratedColumn({name:'ID'}) id: number }`);
    const sql = gen([longo], { oracle11g: true });
    expect(sql).toContain('CONSTRAINT PK_MOVIMENTACAO_ESTOQUE_FILIAI PRIMARY KEY');
    expect(sql).toContain('CREATE SEQUENCE SQ_MOVIMENTACAO_ESTOQUE_FILIAI START');
    expect(gen([longo])).toContain('CONSTRAINT PK_MOVIMENTACAO_ESTOQUE_FILIAIS PRIMARY KEY');
  });

  it('coloca aspas em colunas com palavra reservada do Oracle e avisa', () => {
    const sql = gen([
      parseFile('a.ts', `@Entity('T') class T {
        @PrimaryColumn('number',{name:'LEVEL'}) level: number
        @Column('date',{name:'DATE'}) date: Date
        @Index() @Column('number',{name:'SIZE'}) size: number }`),
    ]);
    expect(sql).toMatch(/\n\s+"LEVEL"\s+NUMBER NOT NULL,/);
    expect(sql).toMatch(/\n\s+"DATE"\s+DATE NOT NULL,/);
    expect(sql).toContain('PRIMARY KEY ("LEVEL")');
    expect(sql).toContain('COMMENT ON COLUMN T."DATE"');
    expect(sql).toContain('ON T ("SIZE")');
    expect(sql).toContain('-- ATENÇÃO: "DATE" é palavra reservada do Oracle; o nome vai entre aspas');
  });

  it('mesma tabela em duas entities sai uma vez', () => {
    const sql = gen([
      parseFile('a.ts', `@Entity('T') class A { @PrimaryColumn('number',{name:'ID'}) id: number }`),
      parseFile('b.ts', `@Entity('T') class B { @PrimaryColumn('number',{name:'ID'}) id: number }`),
    ]);
    expect(sql.match(/CREATE TABLE T \(/g)).toHaveLength(1);
  });
});
