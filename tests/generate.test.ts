import { describe, it } from 'vitest';
import { parseFixture, assert } from './helpers';
import { buildReports } from '../src/lib/analysis/classify';
import { generateDdl } from '../src/lib/ddl/generate';
import { parseFile } from '../src/lib/parser/parseFile';


function gen(files, opts = { oracle11g: false }) {
  const { reports, registry } = buildReports(files);
  const usable = reports.filter((r) => ['ok', 'assumptions', 'revised'].includes(r.status) || r.kind === 'view');
  return generateDdl(usable, registry, opts, { source: 'teste', now: new Date(2026, 10, 13, 10, 0) });
}

const all = () => ['Cliente', 'Produto', 'Categoria', 'Marca', 'ClienteResumoV'].map(parseFixture);

describe('generateDdl', () => {
  it('gera CREATE TABLE com PK, default e NOT NULL', () => {
    const sql = gen(all());
    assert.ok(sql.includes('CREATE TABLE LOJA.CLIENTE ('));
    assert.ok(sql.includes('CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE)'));
    assert.match(sql, /DATA_CADASTRO\s+DATE\s+DEFAULT SYSDATE NOT NULL/);
    assert.match(sql, /ATIVO\s+NUMBER\s+NOT NULL/);
    assert.match(sql, /\n\s+NOME\s+VARCHAR2\(255\),/);
    assert.ok(sql.includes("COMMENT ON TABLE LOJA.CLIENTE IS 'Entity Cliente (loja/Cliente.ts)';"));
  });

  it('usa IDENTITY por padrão', () => {
    const sql = gen(all());
    assert.match(sql, /ID_PRODUTO\s+NUMBER GENERATED BY DEFAULT AS IDENTITY/);
    assert.ok(!sql.includes('CREATE SEQUENCE'));
  });

  it('com Oracle 11g usa SEQUENCE', () => {
    const sql = gen(all(), { oracle11g: true });
    assert.ok(sql.includes('CREATE SEQUENCE SQ_PRODUTO START WITH 1 INCREMENT BY 1 NOCACHE;'));
    assert.ok(!sql.includes('IDENTITY'));
  });

  it('marca suposições com ATENÇÃO', () => {
    assert.ok(gen(all()).includes('-- ATENÇÃO: tamanho não definido na entity; usado VARCHAR2(255)'));
  });

  it('FK incompatível sai comentada com o motivo', () => {
    const sql = gen(all());
    assert.ok(sql.includes('-- ALTER TABLE PRODUTO ADD CONSTRAINT FK_PRODUTO_ID_MARCA FOREIGN KEY (ID_MARCA) REFERENCES MARCA (COD_MARCA);'));
    assert.match(sql, /-- MOTIVO: .*ORA-02267/);
  });

  it('FK compatível sai ativa', () => {
    const sql = gen([
      parseFile('a.ts', `@Entity('PAI') class Pai { @PrimaryGeneratedColumn({name:'ID'}) id: number }`),
      parseFile('b.ts', `@Entity('FILHO') class Filho { @PrimaryGeneratedColumn({name:'ID'}) id: number
        @ManyToOne(() => Pai) @JoinColumn({name:'PAI_ID'}) pai: Pai }`),
    ]);
    assert.match(sql, /^ALTER TABLE FILHO ADD CONSTRAINT FK_FILHO_PAI_ID FOREIGN KEY \(PAI_ID\) REFERENCES PAI \(ID\);$/m);
  });

  it('lista views no fim, sem DDL', () => {
    const sql = gen(all());
    const idx = sql.indexOf('Views encontradas (sem DDL)');
    assert.ok(idx > 0);
    assert.ok(sql.slice(idx).includes('CLIENTE_RESUMO_V'));
    assert.ok(sql.slice(idx).includes('ID_GRUPO'));
    assert.ok(!sql.includes('CREATE TABLE CLIENTE_RESUMO_V'));
  });

  it('escapa aspas simples nos comentários', () => {
    const sql = gen([parseFile("o'brien.ts", `@Entity('T') class T { @PrimaryColumn('number',{name:'ID'}) id: number }`)]);
    assert.ok(sql.includes("IS 'Entity T (o''brien.ts)';"));
  });

  it('trunca nomes de constraint a 30 com Oracle 11g', () => {
    const longo = parseFile('x.ts', `@Entity('MOVIMENTACAO_ESTOQUE_FILIAIS') class Mov { @PrimaryGeneratedColumn({name:'ID'}) id: number }`);
    const sql = gen([longo], { oracle11g: true });
    assert.ok(sql.includes('CONSTRAINT PK_MOVIMENTACAO_ESTOQUE_FILIAI PRIMARY KEY'));
    assert.ok(sql.includes('CREATE SEQUENCE SQ_MOVIMENTACAO_ESTOQUE_FILIAI START'));
    assert.ok(gen([longo]).includes('CONSTRAINT PK_MOVIMENTACAO_ESTOQUE_FILIAIS PRIMARY KEY'));
  });

  it('coloca aspas em colunas com palavra reservada do Oracle e avisa', () => {
    const sql = gen([
      parseFile('a.ts', `@Entity('T') class T {
        @PrimaryColumn('number',{name:'LEVEL'}) level: number
        @Column('date',{name:'DATE'}) date: Date
        @Index() @Column('number',{name:'SIZE'}) size: number }`),
    ]);
    assert.match(sql, /\n\s+"LEVEL"\s+NUMBER NOT NULL,/);
    assert.match(sql, /\n\s+"DATE"\s+DATE NOT NULL,/);
    assert.ok(sql.includes('PRIMARY KEY ("LEVEL")'));
    assert.ok(sql.includes('COMMENT ON COLUMN T."DATE"'));
    assert.ok(sql.includes('ON T ("SIZE")'));
    assert.ok(sql.includes('-- ATENÇÃO: "DATE" é palavra reservada do Oracle; o nome vai entre aspas'));
  });

  it('mesma tabela em duas entities sai uma vez', () => {
    const sql = gen([
      parseFile('a.ts', `@Entity('T') class A { @PrimaryColumn('number',{name:'ID'}) id: number }`),
      parseFile('b.ts', `@Entity('T') class B { @PrimaryColumn('number',{name:'ID'}) id: number }`),
    ]);
    assert.equal(sql.match(/CREATE TABLE T \(/g).length, 1);
  });
});
